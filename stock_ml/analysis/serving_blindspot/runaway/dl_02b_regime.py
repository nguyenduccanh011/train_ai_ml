"""Regime split >=2022 cho DLT_* vs BASE tu yearly returns cua dl_02."""
import math

YEARS_GE22 = (4 * 365 + 188) / 365.25  # 2022-01-01 -> 2026-07-08

series = {
    "BASE":        {2020: .926, 2021: 1.216, 2022: .319, 2023: .354, 2024: .212, 2025: .427, 2026: .095},
    "DLT_90_10_X05": {2020: .856, 2021: 1.230, 2022: .296, 2023: .344, 2024: .201, 2025: .418, 2026: .089},
    "DLT_80_20_X05": {2020: .785, 2021: 1.245, 2022: .271, 2023: .333, 2024: .188, 2025: .408, 2026: .082},
    "DLT_MG_X05":  {2020: 1.017, 2021: 1.958, 2022: .211, 2023: .328, 2024: .113, 2025: .451, 2026: .022},
    "DLT_MG_X03":  {2020: 1.166, 2021: 2.082, 2022: .191, 2023: .323, 2024: .124, 2025: .524, 2026: -.018},
}

print(f"{'kich ban':<15}{'growth>=22':>11}{'CAGR>=22':>10}{'growth 20-21':>13}")
for name, y in series.items():
    g22 = math.prod(1 + y[k] for k in (2022, 2023, 2024, 2025, 2026))
    g2021 = math.prod(1 + y[k] for k in (2020, 2021))
    cagr22 = g22 ** (1 / YEARS_GE22) - 1
    print(f"{name:<15}{g22:>11.3f}{cagr22*100:>9.2f}%{g2021:>13.3f}")
